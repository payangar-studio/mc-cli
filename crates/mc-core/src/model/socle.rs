//! `<socle dir>/socle.toml` and `<socle dir>/socle.lock`: the socle's own
//! records in the repository.
//!
//! The socle version is the version of the CLI that last wrote the socle:
//! every command compares it to its own.

use std::cmp::Ordering;
use std::path::Path;

use semver::Version;
use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};

use crate::error::{Error, Result};
use crate::socle::Socle;

/// `<socle dir>/socle.toml`: the socle version, and the values `init` was
/// given, of the project type's own type `I`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SocleConfig<I> {
    /// Version of the CLI that last wrote the socle.
    pub version: String,
    pub init: I,
}

impl<I: Serialize + DeserializeOwned> SocleConfig<I> {
    pub fn parse(socle: &Socle, text: &str) -> Result<Self> {
        super::parse_toml(
            text,
            &socle.config_path(),
            &format!(
                "restore it from git history, or rerun `{} init` in a new directory",
                socle.bin
            ),
        )
    }

    pub fn to_toml(&self, socle: &Socle) -> String {
        format!(
            "# Managed by {}. `{} update` rewrites the version and keeps the values.\n\n{}",
            socle.tool,
            socle.bin,
            super::to_toml(self)
        )
    }

    /// Reads the socle settings under the repository root.
    pub fn load(socle: &Socle, root: &Path) -> Result<Self> {
        Self::parse(socle, &super::read_file(&root.join(socle.config_path()))?)
    }

    pub fn save(&self, socle: &Socle, root: &Path) -> Result<()> {
        super::write_file(&root.join(socle.config_path()), &self.to_toml(socle))
    }
}

/// `<socle dir>/socle.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SocleLock {
    #[serde(default)]
    pub files: Vec<LockedFile>,
}

/// One thing the socle wrote.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedFile {
    /// Path relative to the repository root, with `/` separators.
    pub path: String,
    /// sha256 of what the socle wrote: the whole file, or the block between
    /// its markers.
    pub sha256: String,
    pub kind: LockedKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum LockedKind {
    /// A file the socle owns entirely.
    File,
    /// A block between markers in a file the project owns otherwise.
    Block,
}

impl SocleLock {
    pub fn parse(socle: &Socle, text: &str) -> Result<Self> {
        super::parse_toml(
            text,
            &socle.lock_path(),
            &format!(
                "restore it from git history; `{} update --force` rewrites it",
                socle.bin
            ),
        )
    }

    /// The canonical text, sorted by path.
    pub fn to_toml(&self, socle: &Socle) -> String {
        let mut sorted = self.clone();
        sorted.files.sort_by(|a, b| a.path.cmp(&b.path));
        format!(
            "# Generated by {}: files the socle wrote. Do not edit by hand.\n\n{}",
            socle.tool,
            super::to_toml(&sorted)
        )
    }

    pub fn load(socle: &Socle, root: &Path) -> Result<Self> {
        Self::parse(socle, &super::read_file(&root.join(socle.lock_path()))?)
    }

    pub fn save(&self, socle: &Socle, root: &Path) -> Result<()> {
        super::write_file(&root.join(socle.lock_path()), &self.to_toml(socle))
    }
}

/// How the repository's socle version compares to the CLI's.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum VersionCheck {
    Equal,
    /// The repository can be brought to the CLI's version with `update`.
    RepoOlder {
        repo: Version,
        cli: Version,
    },
    /// The CLI does not know this socle's format yet.
    RepoNewer {
        repo: Version,
        cli: Version,
    },
}

/// Compares the repository's socle version to `cli`.
pub fn compare_versions(socle: &Socle, repo: &str, cli: &Version) -> Result<VersionCheck> {
    let repo = Version::parse(repo).map_err(|e| {
        Error::usage(
            format!("{} has an invalid version `{repo}`", socle.config_path()),
            "restore the file from git history",
        )
        .with_source(e)
    })?;
    Ok(match repo.cmp(cli) {
        Ordering::Equal => VersionCheck::Equal,
        Ordering::Less => VersionCheck::RepoOlder {
            repo,
            cli: cli.clone(),
        },
        Ordering::Greater => VersionCheck::RepoNewer {
            repo,
            cli: cli.clone(),
        },
    })
}

impl VersionCheck {
    /// What a command does about it: nothing, a warning to show, or a refusal.
    pub fn enforce(&self, socle: &Socle) -> Result<Option<String>> {
        match self {
            VersionCheck::Equal => Ok(None),
            VersionCheck::RepoOlder { repo, cli } => Ok(Some(format!(
                "this repository uses socle {repo}, older than this CLI ({cli}); run `{} update` to bring it up to date",
                socle.bin
            ))),
            VersionCheck::RepoNewer { repo, cli } => Err(Error::usage(
                format!(
                    "this repository uses socle {repo}, newer than this CLI ({cli}), which does not know its format"
                ),
                format!("upgrade {} to {repo} or later", socle.tool),
            )),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::error::ErrorKind;
    use crate::socle::TEST;

    fn v(s: &str) -> Version {
        Version::parse(s).unwrap()
    }

    #[test]
    fn lock_is_written_sorted_by_path() {
        let entry = |path: &str| LockedFile {
            path: path.into(),
            sha256: "0".repeat(64),
            kind: LockedKind::File,
        };
        let lock = SocleLock {
            files: vec![entry("b"), entry("a")],
        };
        let text = lock.to_toml(&TEST);
        assert!(text.starts_with("# Generated by test-cli: "));
        assert!(text.find("path = \"a\"").unwrap() < text.find("path = \"b\"").unwrap());
    }

    #[test]
    fn equal_versions_say_nothing() {
        let check = compare_versions(&TEST, "0.3.0", &v("0.3.0")).unwrap();
        assert_eq!(check, VersionCheck::Equal);
        assert_eq!(check.enforce(&TEST).unwrap(), None);
    }

    #[test]
    fn older_repository_warns_and_suggests_update() {
        let check = compare_versions(&TEST, "0.2.9", &v("0.3.0")).unwrap();
        assert!(matches!(check, VersionCheck::RepoOlder { .. }));
        let warning = check.enforce(&TEST).unwrap().unwrap();
        assert!(warning.contains("test update"));
    }

    #[test]
    fn newer_repository_is_refused() {
        let check = compare_versions(&TEST, "0.4.0", &v("0.3.0")).unwrap();
        assert!(matches!(check, VersionCheck::RepoNewer { .. }));
        let err = check.enforce(&TEST).unwrap_err();
        assert!(err.to_string().contains("newer than this CLI"));
        assert_eq!(err.hint(), "upgrade test-cli to 0.4.0 or later");
    }

    #[test]
    fn prereleases_order_before_their_release() {
        let check = compare_versions(&TEST, "0.3.0-rc1", &v("0.3.0")).unwrap();
        assert!(matches!(check, VersionCheck::RepoOlder { .. }));
    }

    #[test]
    fn invalid_version_is_reported() {
        let err = compare_versions(&TEST, "latest", &v("0.3.0")).unwrap_err();
        assert_eq!(err.kind(), ErrorKind::Usage);
        assert!(
            err.to_string()
                .contains(".test/socle.toml has an invalid version `latest`")
        );
    }
}
